/**
 * `piano install-mcp` — register Piano's stdio MCP server with the coding
 * agents the user already has.
 *
 * Claude Code and Codex have first-party `mcp add` commands, so this command
 * delegates to them rather than editing their config files. dsh has no
 * equivalent registry; it gets a generated profile patch under Piano's own
 * `~/.piano/dsh` directory, never under `~/.dsh`.
 */
import { io } from "@piano/base";
import { Effect } from "effect";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { agentHome, unusableHome } from "./agent-home.js";
import { CliArgumentError, SkillInstallError } from "./errors.js";
import { programName } from "./program-name.js";

const SIDECAR = fileURLToPath(new URL("./piano-mcp.mjs", import.meta.url));

function dshPatchPath(): string {
  return join(homedir(), ".piano", "dsh", "piano-mcp.yml");
}

type TargetName = "claude" | "codex" | "dsh";

const usage = `usage: ${programName()} install-mcp [--target <claude|codex|dsh|all>] [--dry-run]`;

function parseArgs(args: readonly string[]): Effect.Effect<
  { readonly targets: readonly TargetName[]; readonly dryRun: boolean },
  CliArgumentError
> {
  const names: TargetName[] = [];
  let dryRun = false;
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    if (arg === "--dry-run") {
      dryRun = true;
      continue;
    }
    const value = arg === "--target" ? args[index + 1] : arg?.startsWith("--target=") ? arg.slice(9) : undefined;
    if (arg === "--target") index += 1;
    if (value === undefined) return Effect.fail(new CliArgumentError({ message: `unknown option: ${String(arg)}\n${usage}` }));
    if (value === "all") names.push("claude", "codex", "dsh");
    else if (value === "claude" || value === "codex" || value === "dsh") names.push(value);
    else return Effect.fail(new CliArgumentError({ message: `unknown target: ${value}\n${usage}` }));
  }
  if (names.length === 0) names.push("claude", "codex", "dsh");
  return Effect.succeed({ targets: [...new Set(names)], dryRun });
}

function report(line: string): Effect.Effect<void> {
  return Effect.sync(() => console.log(line));
}

const failed = (path: string, cause: unknown): SkillInstallError => new SkillInstallError({
  operation: "install-mcp",
  path,
  message: cause instanceof Error ? cause.message : String(cause),
});

/** Run a host CLI with the caller's environment. `NOT_STARTED` means the
 * binary is missing, which is a skip rather than a failed install; a hang is a
 * real failure and must not be reported as "not installed". */
function runHost(command: string, args: readonly string[]): Effect.Effect<number, never> {
  return io.execFileResult(command, args, { timeoutMs: 30_000 }).pipe(
    Effect.map((result) => result.code),
    Effect.catchAll(() => Effect.succeed(io.NOT_STARTED)),
  );
}

/** Register the server with a host that has its own `mcp add`. The two hosts
 * differ only in where `piano` sits in the argv and in their wording. */
function installHost(name: "claude" | "codex", scope: readonly string[], dryRun: boolean): Effect.Effect<void, SkillInstallError> {
  return Effect.gen(function* () {
    const hostHome = agentHome(name);
    const unusable = yield* unusableHome(hostHome);
    if (unusable !== undefined) {
      yield* report(`[WARN] ${name}: skipped (${unusable === "missing" ? "home not found" : "home is not a directory"})`);
      return;
    }
    const existing = yield* runHost(name, ["mcp", "get", "piano"]);
    if (existing === 0) {
      yield* report(`[PASS] ${name}: piano MCP server already configured`);
      return;
    }
    if (existing === io.NOT_STARTED) {
      yield* report(`[WARN] ${name}: skipped (${name} CLI not found)`);
      return;
    }
    if (existing === io.TIMED_OUT) {
      return yield* Effect.fail(failed(hostHome, new Error(`${name} mcp get did not answer within 30s`)));
    }
    const args = ["mcp", "add", ...scope, "piano", "--", process.execPath, SIDECAR];
    if (dryRun) {
      yield* report(`[INFO] ${name}: would run ${name} ${args.join(" ")}`);
      return;
    }
    const added = yield* io.execFile(name, args, { timeoutMs: 30_000 }).pipe(
      Effect.mapError((cause) => failed(hostHome, cause)),
    );
    if (added.code !== 0) return yield* Effect.fail(failed(hostHome, new Error(added.stderr || `${name} mcp add failed`)));
    yield* report(`[PASS] ${name}: registered piano MCP server`);
  });
}

/** The first line of every patch this command writes. It marks the file as
 * Piano's to replace; a file without it belongs to the user. */
const GENERATED_MARKER = "# Generated by Piano: mounts the Piano MCP server for /piano.";

function dshPatch(): string {
  return [
    GENERATED_MARKER,
    "- insert:",
    "    - id: piano-mcp",
    "      name: '@deepseek-ai/dsh-mcp-client'",
    "      config:",
    "        serverName: piano",
    "        transport: stdio",
    "        command: !!js process.execPath",
    "        args:",
    `          - ${JSON.stringify(SIDECAR)}`,
    "        failOnStartupError: true",
    "        toolCallTimeoutMs: 3600000",
    "",
  ].join("\n");
}

function installDsh(dryRun: boolean): Effect.Effect<void, SkillInstallError> {
  return Effect.gen(function* () {
    const unusable = yield* unusableHome(agentHome("dsh"));
    if (unusable !== undefined) {
      yield* report(`[WARN] dsh: skipped (${unusable === "missing" ? "home not found" : "home is not a directory"})`);
      return;
    }
    const patch = dshPatch();
    const target = dshPatchPath();
    const current = yield* Effect.either(io.readText(target));
    const stale = current._tag === "Right" && current.right !== patch;
    if (current._tag === "Right" && !stale) {
      yield* report(`[PASS] dsh: up-to-date (${target})`);
      return;
    }
    // The sidecar and interpreter are absolute paths, so an upgrade or an nvm
    // switch makes the generated patch stale. A file this command wrote is
    // replaced; a file the user edited starts differently and stays untouched.
    if (stale && !current.right.startsWith(GENERATED_MARKER)) {
      yield* report(`[WARN] dsh: conflict (${target} was edited; left untouched)`);
      return;
    }
    if (dryRun) {
      yield* report(`[INFO] dsh: would ${stale ? "update" : "write"} ${target}`);
      return;
    }
    yield* io.mkdir(dirname(target), { recursive: true, mode: 0o755 }).pipe(
      Effect.mapError((cause) => failed(target, cause)),
    );
    const written = stale
      // Temp then rename, so a killed update never leaves a half-written patch.
      ? yield* io.writeFile(`${target}.tmp-${String(process.pid)}`, patch).pipe(
        Effect.flatMap(() => io.rename(`${target}.tmp-${String(process.pid)}`, target)),
        Effect.as(true),
        Effect.mapError((cause) => failed(target, cause)),
      )
      : yield* io.createExclusive(target, patch).pipe(Effect.mapError((cause) => failed(target, cause)));
    if (!written) {
      yield* report(`[WARN] dsh: conflict (${target} appeared concurrently); left untouched`);
      return;
    }
    yield* report(`[PASS] dsh: ${stale ? "updated" : "wrote"} ${target}; add it with --patch or to your profile`);
  });
}

export function installMcpCommand(args: readonly string[]): Effect.Effect<void, CliArgumentError | SkillInstallError> {
  return Effect.gen(function* () {
    const options = yield* parseArgs(args);
    const failures: SkillInstallError[] = [];
    // One target's failure must not stop the others: a missing host binary is
    // a skip, and every remaining agent still gets its setup. Each failure is
    // reported and the run exits non-zero once all targets have been tried.
    for (const target of options.targets) {
      const step = target === "claude" ? installHost("claude", ["--scope", "user"], options.dryRun)
        : target === "codex" ? installHost("codex", [], options.dryRun)
        : installDsh(options.dryRun);
      const outcome = yield* Effect.either(step);
      if (outcome._tag === "Left") {
        failures.push(outcome.left);
        yield* report(`[FAIL] ${target}: ${outcome.left.message}`);
      }
    }
    if (failures.length > 0) return yield* Effect.fail(failures[0]!);
  });
}
